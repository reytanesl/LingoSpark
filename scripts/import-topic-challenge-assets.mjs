const cueMap = {};
for (const file of files) {
  if (!file.includes('kw2-')) continue;
  const slug = cueSlugFromUpload(file);
  if (!slug) {
    console.warn('skip kw2 parse fail', file.slice(-80));
    continue;
  }
  const dest = path.join(topicCuesDir, `${slug}.png`);
  fs.copyFileSync(path.join(srcDir, file), dest);
  const rel = `assets/topic-cues/${slug}.png`;
  cueMap[slug] = { img: rel, words: cueAliases[slug] || [slug.split('-').pop()] };
  console.log('cue', slug);
}

const cuesOut = `/**
 * Topic Challenge — optional picture cues (kw2 sticker art).
 * Auto-generated by scripts/import-topic-challenge-assets.mjs
 */
(function (global) {
  'use strict';
  global.PE_TOPIC_CHALLENGE_CUE_IMAGES = ${JSON.stringify(cueMap, null, 2)};

  global.peTopicChallengeCueImg = function peTopicChallengeCueImg(text) {
    const hay = String(text || '').toLowerCase();
    if (!hay) return null;
    const map = global.PE_TOPIC_CHALLENGE_CUE_IMAGES || {};
    for (const slug of Object.keys(map)) {
      const entry = map[slug];
      const words = entry.words || [];
      for (const w of words) {
        const needle = String(w).toLowerCase();
        if (needle.length >= 3 && hay.includes(needle)) return entry.img;
      }
    }
    return null;
  };
})(typeof window !== 'undefined' ? window : globalThis);
`;

fs.writeFileSync(path.join(root, 'pe-topic-challenge-cues.js'), cuesOut);

