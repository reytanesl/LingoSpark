export function t(lang, key) {
  const pack = STRINGS[normalizeLanguage(lang)] || STRINGS.en;
  return pack[key] ?? STRINGS.en[key] ?? key;
}

export function taskLabel(lang, id) {
  const pack = TASKS[normalizeLanguage(lang)] || TASKS.en;
  return pack[id] || TASKS.en[id] || id;
}

export function tfWords(lang) {
  return {
    true: t(lang, 'tfTrue'),
    false: t(lang, 'tfFalse'),
  };
}
